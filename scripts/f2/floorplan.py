"""Writes the core's F2 floorplan, platforms/f2/core/small_shell_cl_pnr_user.xdc.

AWS's build reads that file before opt_design and place_design
(build_level_1_cl.tcl); scripts/f2/build_cl.sh copies it into the CL's
build/constraints. Soft SLR assignments (USER_SLR_ASSIGNMENT), not
pblocks (PLAN.md M10, "Approach"):

- SLR0, beside the HBM: the HBM's register stages, port 0's merge and the
  host's side of it, the ILA, and the engine's groups 0 .. 3 (ports 0 .. 15,
  their DMAs and lanes).
- SLR1: the engine's groups 4 .. 7, the engine's central logic (issue, step,
  drain), the controller.
- SLR2: the vector unit and the core's registers on its side (xv_*).

Every assignment is to cells that no other line covers (a hierarchical
cell or the primitives at one level), so no cell has two. The crossings
have a register on at least one side and at most a few LUTs on the other,
none crosses two SLRs: the stages in platforms/f2/core/f2_core.sv,
rtl/core.sv's xv_ registers and vector-unit command queues, the engine's
per-group and per-half registers (rtl/engine.sv). Some crossings still
have logic after them (the engine's DMA commands, the lanes' pops, the
stages' enables). The lanes of a group stay together with their DMAs, so
no lane spans two SLRs (core build 2's worst paths).

    python3 scripts/f2/floorplan.py          # rewrite the file
    python3 scripts/f2/floorplan.py --check  # exit 1 if it is out of date
"""

import argparse
import sys
from pathlib import Path

PORTS = 32
LANES_PER_PORT = 4  # rtl/engine.sv: DataWidth / (16 * E)
GROUP_PORTS = 4  # rtl/engine.sv's GP
GROUPS = PORTS // GROUP_PORTS
SLR0_GROUPS = 4  # groups 0 .. 3 in SLR0, the others in SLR1

CL = "WRAPPER/CL"
F2 = f"{CL}/u_core"  # f2_core
CORE = f"{F2}/u_core"  # core
ENGINE = f"{CORE}/u_engine"
# rtl/engine.sv's generate blocks that belong to a group (the rest is central)
GROUP_BLOCKS = ("gen_group", "gen_seen", "gen_drain")
HALF_BLOCK = "gen_half"  # rtl/engine.sv: half h of the groups (0: groups 0 .. 3)

OUT = Path(__file__).resolve().parents[2] / "platforms/f2/core/small_shell_cl_pnr_user.xdc"

HEADER = """\
# SPDX-License-Identifier: Apache-2.0 WITH SHL-2.1
# Copyright 2026 The Cabosse Authors
#
# Generated by scripts/f2/floorplan.py: edit that, not this file.
# The core's floorplan on F2 (soft SLR assignments); the script says why.
"""


def esc(name: str) -> str:
    """A cell name as a get_cells pattern: brackets escaped."""
    return name.replace("[", "\\[").replace("]", "\\]")


def assign(slr: int, pattern: str) -> str:
    return f"set_property USER_SLR_ASSIGNMENT SLR{slr} [get_cells {{{pattern}}}]"


def assign_filtered(slr: int, pattern: str, exclude: list[str]) -> str:
    cond = " && ".join(f'NAME !~ "{x}"' for x in exclude)
    return f"set_property USER_SLR_ASSIGNMENT SLR{slr} [get_cells -filter {{{cond}}} {{{pattern}}}]"


def group_slr(group: int) -> int:
    return 0 if group < SLR0_GROUPS else 1


def lines() -> list[str]:
    out = [HEADER]

    out.append("# The engine: each group's lanes, DMAs and registers in the group's SLR")
    for p in range(PORTS):
        slr = group_slr(p // GROUP_PORTS)
        out.append(assign(slr, esc(f"{ENGINE}/gen_dma[{p}].") + "*"))
        for i in range(LANES_PER_PORT):
            out.append(assign(slr, esc(f"{ENGINE}/gen_lane[{p * LANES_PER_PORT + i}].") + "*"))
    for g in range(GROUPS):
        for block in GROUP_BLOCKS:
            out.append(assign(group_slr(g), esc(f"{ENGINE}/{block}[{g}].") + "*"))
    for h in range(2):
        out.append(assign(h, esc(f"{ENGINE}/{HALF_BLOCK}[{h}].") + "*"))
    out.append("# ... and the rest of it (issue, step, drain) in SLR1")
    exclude = [f"{ENGINE}/{b}*" for b in ("gen_dma", "gen_lane", *GROUP_BLOCKS, HALF_BLOCK)]
    out.append(assign_filtered(1, f"{ENGINE}/*", exclude))

    out.append("")
    out.append("# The controller, the vector unit and the core's registers on its side")
    # (core.sv's single done and error registers are left to the placer: one
    # register, register to register either way, and a pattern that matched
    # nothing would stop the build.)
    out.append(assign(1, f"{CORE}/u_controller"))
    out.append(assign(1, f"{CORE}/u_vec_cmd0"))
    out.append(assign(2, f"{CORE}/u_vec_cmd1"))
    out.append(assign(2, f"{CORE}/u_vec"))
    out.append(assign(2, f"{CORE}/xv_*"))

    out.append("")
    out.append("# The HBM's stages: the first beside the HBM, the next in the port's group's SLR")
    for p in range(PORTS):
        slr = group_slr(p // GROUP_PORTS)
        hbm = f"{F2}/gen_hbm[{p}]"
        out.append(assign(0, esc(f"{hbm}.u_ar/gen_stage[1].") + "*"))
        out.append(assign(slr, esc(f"{hbm}.u_ar/gen_stage[0].") + "*"))
        if p == 0:
            out.append(assign(0, esc(f"{hbm}.gen_r_pipe.") + "*"))
        else:
            out.append(assign(0, esc(f"{hbm}.gen_r_regs.") + "*0_q_reg*"))
            out.append(assign(slr, esc(f"{hbm}.gen_r_regs.") + "*1_q_reg*"))
    out.append("# Port 0: its write channels, the merge, the host's side")
    for name in ("u_aw", "u_w", "u_b", "u_port0"):
        out.append(assign(0, f"{F2}/{name}"))
    # bringup_host.sv: its logic beside the port; HostStages = 2 per channel,
    # the stage beside the port in SLR0, the other in SLR1 (towards PCIS).
    out.append(assign_filtered(0, f"{F2}/u_host/*", [f"{F2}/u_host/u_*"]))
    for name, near in (("u_ar", 1), ("u_aw", 1), ("u_w", 1), ("u_r", 0), ("u_b", 0)):
        for s in (0, 1):
            pat = esc(f"{F2}/u_host/{name}/gen_stage[{s}].") + "*"
            out.append(assign(0 if s == near else 1, pat))
    out.append("# The vector unit's AXI: one stage per SLR")
    for name in ("u_v_ar", "u_v_aw", "u_v_w"):  # stage 0 beside the vector unit
        for s, slr in enumerate((2, 1, 0)):
            out.append(assign(slr, esc(f"{F2}/{name}/gen_stage[{s}].") + "*"))
    for name in (
        "v_r_q_reg",
        "v_r_valid_q_reg",
        "v_b_q_reg",
        "v_b_valid_q_reg",
    ):  # stage 0 beside port 0
        for s, slr in enumerate((0, 1, 2)):
            out.append(assign(slr, esc(f"{F2}/{name}[{s}]") + "*"))

    out.append("")
    out.append("# The ILA probes port 0's HBM channels")
    out.append(assign(0, f"{CL}/u_ila"))
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is out of date")
    args = parser.parse_args()
    text = "\n".join(lines()) + "\n"
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is out of date: run scripts/f2/floorplan.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
